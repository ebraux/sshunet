    "## 3. Génération de données SSH synthétiques\n",
    "\n",
    "Nous allons créer un dataset synthétique qui imite les motifs de hauteur de surface de la mer, avec :\n",
    "- Des ondes de base (représentant des courants)\n",
    "- Des tourbillons (eddies) aléatoires\n",
    "- Du bruit pour simuler des perturbations"

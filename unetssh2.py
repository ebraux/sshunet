    "class LightSSHDataset(Dataset):\n",
    "    \"\"\"Dataset SSH synthétique léger pour tests sans GPU\"\"\"\n",
    "    def __init__(self, num_samples=100, size=64, noise_level=0.05, is_train=True):\n",
    "        \"\"\"\n",
    "        Args:\n",
    "            num_samples: Nombre d'échantillons à générer\n",
    "            size: Taille des images (size x size)\n",
    "            noise_level: Niveau de bruit à ajouter\n",
    "            is_train: Si True, génère les données d'entrée avec du bruit\n",
    "        \"\"\"\n",
    "        self.size = size\n",
    "        self.num_samples = num_samples\n",
    "        self.noise_level = noise_level\n",
    "        self.is_train = is_train\n",
    "        self.clean_data, self.noisy_data = self._generate_synthetic_data()\n",
    "        \n",
    "    def _generate_synthetic_data(self):\n",
    "        \"\"\"Génère des données SSH synthétiques avec du bruit\"\"\"\n",
    "        # Créer un tableau pour les données propres et bruitées\n",
    "        clean_data = np.zeros((self.num_samples, 1, self.size, self.size))\n",
    "        \n",
    "        for i in range(self.num_samples):\n",
    "            # Générer une grille\n",
    "            x, y = np.meshgrid(np.linspace(0, 1, self.size), np.linspace(0, 1, self.size))\n",
    "            \n",
    "            # Ondes de base (courants)\n",
    "            seed = np.random.randint(1, 100)\n",
    "            wave = 0.1 * np.sin(seed * np.pi * x) + 0.1 * np.cos((seed-2) * np.pi * y)\n",
    "            \n",
    "            # Ajouter quelques tourbillons aléatoires (eddies)\n",
    "            num_eddies = np.random.randint(1, 4)\n",
    "            for _ in range(num_eddies):\n",
    "                cx, cy = np.random.rand(2)  # Centre du tourbillon\n",
    "                radius = 0.1 + 0.1 * np.random.rand()  # Rayon du tourbillon\n",
    "                strength = 0.2 * np.random.rand()  # Force du tourbillon\n",
    "                dist = np.sqrt((x - cx)**2 + (y - cy)**2)  # Distance au centre\n",
    "                eddy = strength * np.exp(-(dist**2)/(2*radius**2))  # Forme gaussienne\n",
    "                wave += eddy\n",
    "            \n",
    "            clean_data[i, 0] = wave\n",
    "            \n",
    "        # Ajouter du bruit aux données propres pour créer des données bruitées\n",
    "        noise = np.random.normal(0, self.noise_level, clean_data.shape)\n",
    "        noisy_data = clean_data + noise\n",
    "        \n",
    "        # Normaliser les données entre -1 et 1\n",
    "        clean_max = np.max(np.abs(clean_data))\n",
    "        clean_data /= clean_max\n",
    "        noisy_data /= clean_max\n",
    "        \n",
    "        return clean_data, noisy_data\n",
    "        \n",
    "    def __len__(self):\n",
    "        return self.num_samples\n",
    "    \n",
    "    def __getitem__(self, idx):\n",
    "        if self.is_train:\n",
    "            # Pour l'entraînement : données bruitées -> données propres\n",
    "            return {'input': torch.FloatTensor(self.noisy_data[idx]), \n",
    "                    'target': torch.FloatTensor(self.clean_data[idx])}\n",
    "        else:\n",
    "            # Pour l'inférence : juste les données bruitées\n",
    "            return {'input': torch.FloatTensor(self.noisy_data[idx]),\n",
    "                    'target': torch.FloatTensor(self.clean_data[idx])}"
